
import { backgroundServicePlugin } from './BackgroundServicePlugin';
import { contextAnalyzer } from './ContextAnalyzer';
import { permissionManager } from './PermissionManager';
import { actionExecutor, onProactiveAction } from './ActionExecutor';
import { ProactiveAction, ProactiveActionType } from '../../types/proactive';
import { ProactiveSettings, DEFAULT_PROACTIVE_SETTINGS, AIMindMeshServerSettings } from '../../types';
import { logger } from '../logger';
import { activityLogger } from './ActivityLogger';
import { proactiveNotificationService } from './ProactiveNotificationService';
import { getEventsPendingBriefing, buildBriefingPrompt, markEventBriefed } from './meetingBriefingService';

/** A dismissed or accepted suggestion type stays quiet at least this long */
const SUPPRESS_MS = 60 * 60 * 1000;
/** Minimum gap between two context summarization attempts (a failed one would retry every check) */
const SUMMARIZE_COOLDOWN_MS = 60 * 60 * 1000;
const LOW_BATTERY_ACTION = 'enable_power_saver';

class ProactiveService {
    private suggestions: ProactiveAction[] = [];
    private listeners: ((suggestions: ProactiveAction[]) => void)[] = [];
    private isInitialized = false;
    /** Suggestion type -> time until which it is not proposed again */
    private suppressedUntil = new Map<string, number>();
    /** One listener for the whole app life: re-adding it would run every check several times */
    private readonly handleCheck = (timestamp: number) => { void this.handlePeriodicCheck(timestamp); };

    // v4.0.0 — server mode state
    private serverModeActive = false;
    private serverModeListeners: ((active: boolean, message?: string) => void)[] = [];

    /** Subscribe to server-mode banner events */
    onServerModeChange(cb: (active: boolean, message?: string) => void): () => void {
        this.serverModeListeners.push(cb);
        return () => { this.serverModeListeners = this.serverModeListeners.filter(l => l !== cb); };
    }

    private notifyServerModeChange(active: boolean, message?: string) {
        this.serverModeListeners.forEach(cb => cb(active, message));
    }

    async init() {
        if (this.isInitialized) return;
        this.isInitialized = true;

        logger.log('info', '[ProactiveService] Initializing...');

        // Initialize notification service with user settings
        const settings = this.getProactiveSettings();
        await proactiveNotificationService.init(settings);

        // Local checks run in server mode too: they cover device-only data (battery, the
        // on-device agenda, the chat) that the server's insight engine does not see
        backgroundServicePlugin.addListener(this.handleCheck);

        // Listener for actions generated by Executor (e.g. from other flows)
        onProactiveAction('suggestion', async (action) => {
            this.addSuggestion(action);
        });
        // 'chat' actions (meeting briefings) are turned into messages by useProactiveMessage
    }

    /**
     * Called when AIMindMesh Server connection is established: server insights are received.
     */
    enableServerMode(_serverSettings: AIMindMeshServerSettings): void {
        if (this.serverModeActive) return;
        this.serverModeActive = true;
        logger.log('info', '[ProactiveService] Server mode enabled');
        this.notifyServerModeChange(true);
    }

    /**
     * Called when the server goes offline (3 consecutive heartbeat failures).
     */
    disableServerMode(): void {
        if (!this.serverModeActive) return;
        this.serverModeActive = false;
        logger.log('info', '[ProactiveService] Server offline — local proactive mode only');
        this.notifyServerModeChange(false, 'Server offline — local proactive mode active');
    }

    private getProactiveSettings(): ProactiveSettings {
        try {
            const settingsStr = localStorage.getItem('proactive-settings');
            if (settingsStr) {
                return JSON.parse(settingsStr);
            }
        } catch (e) {
            logger.log('error', '[ProactiveService] Failed to load settings', e);
        }
        return DEFAULT_PROACTIVE_SETTINGS;
    }

    private isSuppressed(type: string, now: number): boolean {
        return (this.suppressedUntil.get(type) ?? 0) > now;
    }

    private hasSuggestion(predicate: (s: ProactiveAction) => boolean): boolean {
        return this.suggestions.some(predicate);
    }

    private async handlePeriodicCheck(timestamp: number) {
        logger.log('info', `[ProactiveService] Handling check at ${timestamp}`);

        const settings = this.getProactiveSettings();
        if (!settings.enabled) return;

        try {
            const context = await contextAnalyzer.analyze();
            logger.log('debug', '[ProactiveService] Context evaluated', context);
            const now = Date.now();
            this.pruneSuggestions(now, context);

            // --- MVP Heuristics ---
            // 1. Low Battery Warning (one card per low-battery episode)
            const isLowBattery = context.device.batteryLevel < 0.2 && !context.device.isCharging;
            if (isLowBattery && settings.contextAwareness.respectBatteryLevel
                && !this.isSuppressed(ProactiveActionType.SUGGEST_OPTIMIZATION, now)
                && !this.hasSuggestion(s => s.data?.action === LOW_BATTERY_ACTION)) {
                const action: ProactiveAction = {
                    id: `batt-${now}`,
                    type: ProactiveActionType.SUGGEST_OPTIMIZATION,
                    category: 'suggestive',
                    priority: 8,
                    triggeredAt: now,
                    triggeredBy: 'system_battery_monitor',
                    expiresAt: now + 1000 * 60 * 30, // 30m
                    status: 'pending',
                    requiresConfirmation: false,
                    dismissible: true,
                    logLevel: 'info',
                    data: {
                        title: 'Low Battery',
                        message: 'Battery is below 20%. I suggest enabling power saver mode.',
                        action: LOW_BATTERY_ACTION
                    }
                };
                await this.processAction(action, context);
            }

            // 2. Overdue Tasks
            if (context.data.overdueTasks.length > 0
                && !this.isSuppressed(ProactiveActionType.SUGGEST_TASK_REVIEW, now)
                && !this.hasSuggestion(s => s.type === ProactiveActionType.SUGGEST_TASK_REVIEW)) {
                const count = context.data.overdueTasks.length;
                const action: ProactiveAction = {
                    id: `overdue-${now}`,
                    type: ProactiveActionType.SUGGEST_TASK_REVIEW,
                    category: 'suggestive',
                    priority: 5,
                    triggeredAt: now,
                    triggeredBy: 'system_task_monitor',
                    expiresAt: now + 1000 * 60 * 60 * 4, // 4h
                    status: 'pending',
                    requiresConfirmation: true,
                    dismissible: true,
                    logLevel: 'info',
                    data: {
                        title: 'Overdue Tasks',
                        message: `You have ${count} overdue tasks. Would you like to review them?`,
                        action: 'review_tasks'
                    }
                };
                await this.processAction(action, context);
            }

            // 3. Meeting Briefing (shortly before upcoming events)
            if (context.data.upcomingEvents && context.data.upcomingEvents.length > 0) {
                const pendingBriefings = getEventsPendingBriefing(
                    context.data.upcomingEvents,
                    settings.contextAwareness.meetingBriefingLeadTimeMinutes,
                    now
                );
                for (const event of pendingBriefings) {
                    const action: ProactiveAction = {
                        id: `briefing-${event.id}-${now}`,
                        type: ProactiveActionType.CHAT_MEETING_BRIEFING,
                        category: 'interactive',
                        priority: 7,
                        triggeredAt: now,
                        triggeredBy: 'system_calendar_monitor',
                        expiresAt: event.start, // Expires when meeting starts
                        status: 'pending',
                        requiresConfirmation: false,
                        dismissible: true,
                        logLevel: 'info',
                        data: {
                            title: `📋 Meeting Briefing: ${event.title}`,
                            message: buildBriefingPrompt(event),
                            eventId: event.id,
                            eventTitle: event.title,
                            eventStart: event.start,
                            action: 'meeting_briefing'
                        }
                    };
                    markEventBriefed(event.id);
                    await this.processAction(action, context);
                }
            }

            // 4. Memory Maintenance (ONLY when idle or charging, ensuring we don't block user)
            if (context.data.memoryCount > 50 &&
                (context.user.activity === 'idle' || context.device.isCharging) &&
                context.user.activity !== 'active' &&
                settings.permissions.autonomous) {
                const action: ProactiveAction = {
                    id: `mem-maint-${now}`,
                    type: ProactiveActionType.PERFORM_MEMORY_MAINTENANCE,
                    category: 'autonomous',
                    priority: 3,
                    triggeredAt: now,
                    triggeredBy: 'system_memory_monitor',
                    expiresAt: undefined,
                    status: 'pending',
                    requiresConfirmation: false,
                    dismissible: false,
                    logLevel: 'info',
                    data: {
                        memoryCount: context.data.memoryCount,
                        action: 'optimize_memory'
                    }
                };
                // Check if we already performed maintenance recently (within last 24h)
                const lastMaintenance = await activityLogger.getLastActionTime(ProactiveActionType.PERFORM_MEMORY_MAINTENANCE);
                const hoursSinceLast = lastMaintenance ? (now - lastMaintenance) / (1000 * 60 * 60) : 999;
                if (hoursSinceLast > 24) {
                    await this.processAction(action, context);
                }
            }

            // 5. Context Summarization (when context reaches threshold)
            if (context.chat.contextUsage >= settings.contextAwareness.summarizationThreshold &&
                settings.contextAwareness.enableAutoSummarization &&
                context.chat.messageCount > 10) {
                const lastAttempt = await activityLogger.getLastActionTime(ProactiveActionType.SUMMARIZE_CONTEXT);
                if (!lastAttempt || now - lastAttempt > SUMMARIZE_COOLDOWN_MS) {
                    const action: ProactiveAction = {
                        id: `ctx-sum-${now}`,
                        type: ProactiveActionType.SUMMARIZE_CONTEXT,
                        category: 'autonomous',
                        priority: 4,
                        triggeredAt: now,
                        triggeredBy: 'system_context_monitor',
                        expiresAt: undefined,
                        status: 'pending',
                        requiresConfirmation: false,
                        dismissible: false,
                        logLevel: 'info',
                        data: {
                            currentUsage: context.chat.contextUsage,
                            messageCount: context.chat.messageCount,
                            threshold: settings.contextAwareness.summarizationThreshold
                        }
                    };
                    await this.processAction(action, context);
                }
            }

        } catch (e) {
            logger.log('error', '[ProactiveService] Error in periodic check', e);
        }
    }

    /** Drops expired cards and the ones whose condition is over (battery charging, no overdue tasks). */
    private pruneSuggestions(now: number, context: { device: { batteryLevel: number; isCharging: boolean }; data: { overdueTasks: unknown[] } }) {
        const batteryOk = context.device.isCharging || context.device.batteryLevel >= 0.2;
        const kept = this.suggestions.filter(s =>
            !(s.expiresAt && s.expiresAt < now) &&
            !(batteryOk && s.data?.action === LOW_BATTERY_ACTION) &&
            !(context.data.overdueTasks.length === 0 && s.type === ProactiveActionType.SUGGEST_TASK_REVIEW)
        );
        if (kept.length !== this.suggestions.length) {
            this.suggestions = kept;
            this.notifyListeners();
        }
    }

    private async processAction(action: ProactiveAction, context: any) {
        const permission = await permissionManager.checkPermission(action.type, context, action.priority);

        if (permission.allowed) {
            if (action.category === 'suggestive') {
                this.addSuggestion(action);
            } else {
                await actionExecutor.execute(action);
            }
        } else {
            logger.log('info', `[ProactiveService] Action blocked: ${permission.reason}`);
            action.status = 'ignored';
            await activityLogger.log(action);
        }
    }

    // --- State Management ---

    getSuggestions() {
        return this.suggestions;
    }

    addSuggestion(action: ProactiveAction) {
        // Deduplicate
        if (this.suggestions.some(s => s.id === action.id)) return;

        this.suggestions = [action, ...this.suggestions];
        this.notifyListeners();

        // Log visibility
        activityLogger.log({ ...action, status: 'pending' });
    }

    private removeSuggestion(action: ProactiveAction) {
        this.suggestions = this.suggestions.filter(s => s.id !== action.id);
        this.notifyListeners();
        // Not proposed again right away (a check runs every 15 minutes)
        this.suppressedUntil.set(action.type, Math.max(action.expiresAt ?? 0, Date.now() + SUPPRESS_MS));
    }

    dismissSuggestion(id: string) {
        const action = this.suggestions.find(s => s.id === id);
        if (!action) return;
        this.removeSuggestion(action);
        activityLogger.logInteraction(id, 'dismissed');
    }

    async acceptSuggestion(action: ProactiveAction) {
        this.removeSuggestion(action);
        activityLogger.logInteraction(action.id, 'clicked');

        // A suggestion card is accepted here: executing it as a suggestion again would only
        // put the same card back
        if (action.category !== 'suggestive') {
            action.status = 'executing';
            await actionExecutor.execute(action);
            return;
        }

        if (action.data?.action === 'review_tasks') {
            // Same route as the app shortcut: opens the Agenda on the task board
            window.dispatchEvent(new CustomEvent('shortcutAction', { detail: 'kanban' }));
        }
        // Low battery: the system power saver cannot be switched from the app, the card is an advice
        await activityLogger.log({ ...action, status: 'completed' });
    }

    subscribe(callback: (suggestions: ProactiveAction[]) => void) {
        this.listeners.push(callback);
        callback(this.suggestions);
        return () => {
            this.listeners = this.listeners.filter(cb => cb !== callback);
        };
    }

    private notifyListeners() {
        this.listeners.forEach(cb => cb(this.suggestions));
    }
}

export const proactiveService = new ProactiveService();
